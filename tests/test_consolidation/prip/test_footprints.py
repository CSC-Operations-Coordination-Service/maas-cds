@pytest.mark.parametrize(
    "footprint",
    [
        CROSSING_ANTEMERIDIAN_FOOTPRINT_JSON,
        PRIP_S2_DS_CROSSING_ANTEMERIDIAN_FOOTPRINT_JSON,
    ],
    ids=["vertex_on_antemeridian", "vertex_near_antemeridian"],
)
def test_correct_footprint_crossing_antemeridian(footprint):
    adjusted_polygon = model.s2_tilpar_tiles.S2Tiles.correct_polygon(
        copy.deepcopy(footprint)
    )

    assert adjusted_polygon["type"] == "MultiPolygon"
    for polygon in adjusted_polygon["coordinates"]:
        for ring in polygon:
            assert ring[0] == ring[-1]
            assert all(-180 <= lon <= 180 for lon, _ in ring)

    adjusted_shape = shape(adjusted_polygon)
    assert adjusted_shape.is_valid
    eastern, western = adjusted_shape.geoms
    assert eastern.bounds[2] == 180
    assert western.bounds[0] == -180

    # the cut keeps the whole footprint, nothing more
    geod = pyproj.Geod(ellps="WGS84")
    lons, lats = zip(*footprint["coordinates"][0])
    footprint_area = abs(geod.polygon_area_perimeter(lons, lats)[0])
    adjusted_area = abs(geod.geometry_area_perimeter(adjusted_shape)[0])
    assert adjusted_area == pytest.approx(footprint_area, rel=1e-3)


